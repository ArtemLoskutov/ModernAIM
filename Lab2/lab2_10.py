from datasets import load_dataset
from transformers import (
    AutoTokenizer,
    AutoModelForSequenceClassification,
    DataCollatorWithPadding,
    Trainer,
    TrainingArguments
)
from sklearn.metrics import accuracy_score, f1_score
import numpy as np
import torch

MODEL_NAME = "distilbert/distilbert-base-uncased"

# data
dataset = load_dataset("stanfordnlp/imdb")

part = dataset["train"].shuffle(seed=42).select(range(1500))
split = part.train_test_split(
    test_size=0.2,
    seed=42,
    stratify_by_column="label"
)

train_data = split["train"]
validation_data = split["test"]
test_data = dataset["test"].shuffle(seed=42).select(range(500))

# tokens + model
tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)

def tokenize(batch):
    return tokenizer(
        batch["text"],
        truncation=True,
        max_length=96
    )

train_data = train_data.map(tokenize, batched=True, remove_columns=["text"])
validation_data = validation_data.map(tokenize, batched=True, remove_columns=["text"])
test_data = test_data.map(tokenize, batched=True, remove_columns=["text"])

model = AutoModelForSequenceClassification.from_pretrained(
    MODEL_NAME,
    num_labels=2
)

# extra
def compute_metrics(result):
    predictions = np.argmax(result.predictions, axis=1)

    return {
        "accuracy": accuracy_score(result.label_ids, predictions),
        "f1": f1_score(result.label_ids, predictions)
    }

# hardest shit
training_args = TrainingArguments(
    output_dir="task10_checkpoints",
    eval_strategy="epoch",
    save_strategy="epoch",
    learning_rate=2e-5,
    weight_decay=0.01,
    per_device_train_batch_size=8,
    per_device_eval_batch_size=16,
    num_train_epochs=2,
    load_best_model_at_end=True,
    metric_for_best_model="f1",
    save_total_limit=1,
    report_to="none",
    seed=67
)

trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=train_data,
    eval_dataset=validation_data,
    processing_class=tokenizer,
    data_collator=DataCollatorWithPadding(tokenizer=tokenizer),
    compute_metrics=compute_metrics
)

trainer.train()

# checking
test = trainer.evaluate(
    test_data,
    metric_key_prefix="test"
)
print("\nTest:")
print("Accuracy:", round(test["test_accuracy"], 4))
print("F1:", round(test["test_f1"], 4))

# manual reviews
reviews = [
    "The film was beautifully directed and the actors gave excellent performances.",
    "The movie was boring, poorly written and full of predictable scenes.",
    "I really enjoyed this story and would gladly watch it again.",
    "The plot was confusing and the ending was disappointing."
]

inputs = tokenizer(
    reviews,
    return_tensors="pt",
    truncation=True,
    padding=True,
    max_length=96
).to(trainer.model.device)

trainer.model.eval()

with torch.no_grad():
    outputs = trainer.model(**inputs)
    probabilities = torch.softmax(outputs.logits, dim=1)

print("\nResults:")

for i in range(len(reviews)):
    scores = probabilities[i]

    if scores[1] > scores[0]:
        result = "POSITIVE"
    else:
        result = "NEGATIVE"

    print("\n", reviews[i])
    print("Negative:", round(scores[0].item(), 4))
    print("Positive:", round(scores[1].item(), 4))
    print("Result:", result)