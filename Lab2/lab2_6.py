from sklearn.datasets import fetch_20newsgroups;
from sklearn.naive_bayes import MultinomialNB;
from sklearn.feature_extraction.text import TfidfTransformer;
from sklearn.feature_extraction.text import CountVectorizer;

#newsgroups = fetch_20newsgroups(subset='all')
#print(newsgroups.target_names)

categories = [
    "alt.atheism",
    "comp.graphics",
    "comp.os.ms-windows.misc",
    "comp.sys.ibm.pc.hardware",
    "comp.sys.mac.hardware"
]

test_sentences = [
    "The article discusses arguments about the existence of God and atheism.",
    "Graphics software renders three dimensional objects using polygons and textures.",
    "Windows crashes after installing a new device driver.",
    "The IBM compatible PC needs a new motherboard and memory modules.",
    "My Macintosh computer needs a replacement hard drive and keyboard."
]

training_data = fetch_20newsgroups(
    subset="train",
    categories=categories,
    shuffle=True,
    random_state=67,
    remove=("headers", "footers", "quotes"),
)

count_vectorizer = CountVectorizer()
train_counts = count_vectorizer.fit_transform(training_data.data)

tfidf_transformer = TfidfTransformer()
train_tfidf = tfidf_transformer.fit_transform(train_counts)

classifier = MultinomialNB()
classifier.fit(train_tfidf, training_data.target)

test_counts = count_vectorizer.transform(test_sentences)
test_tfidf = tfidf_transformer.transform(test_counts)

predictions = classifier.predict(test_tfidf)
probabilities = classifier.predict_proba(test_tfidf)

for index, sentence in enumerate(test_sentences):
    predicted_category = training_data.target_names[predictions[index]]
    confidence = probabilities[index].max()
    print(f"\nSentence: {sentence}")
    print(f"Category: {predicted_category}")
    print(f"Probability: {confidence}")