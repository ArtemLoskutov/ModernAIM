from nltk.corpus import brown

N = 1000
M = 50

brown_words = [word.lower() for word in brown.words()[:N]]
chunks = [brown_words[i:i + M] for i in range(0, len(brown_words), M)]

for i, chunk in enumerate(chunks[:20], start=1):
    print(f"Chunk {i}: {' '.join(chunk)[:50]}...")