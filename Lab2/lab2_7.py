from nltk import NaiveBayesClassifier;
from nltk.classify import accuracy as nltk_accuracy;
from nltk.corpus import names;
import random

#import nltk
#nltk.download('names')

SEED = 67

male_list = [(name, 'male') for name in names.words('male.txt')];
female_list = [(name, 'female') for name in names.words('female.txt')];
data = (male_list + female_list);

rng = random.Random(SEED)
rng.shuffle(data)

split_index = int(0.8 * len(data))
train_data = data[:split_index]
test_data = data[split_index:]

def gender_features(name, n):
    return {"suffix": name[-n:].lower()}

test_names = [
    "Amelia",
    "Charlotte",
    "Samantha",
    "Michael",
    "Christopher",
    "Alexander",
    "Jordan",
    "Taylor",
]

accuracies = {}

for n in range(1, 6):
    train_features = [(gender_features(name, n), gender) for name, gender in train_data]
    test_features = [(gender_features(name, n), gender) for name, gender in test_data]

    classifier = NaiveBayesClassifier.train(train_features)
    accuracy_value = nltk_accuracy(classifier, test_features)
    accuracies[n] = accuracy_value

    print(f"\nN = {n}; Accuracy = {accuracy_value:.4f}")
    print("Results with N parametr:")
    for name in test_names:
        prediction = classifier.classify(gender_features(name, n))
        print(f"  {name}: {prediction}")

best_n = max(accuracies, key=accuracies.get)

print(f"\nBest N: {best_n}")