from nltk.corpus import movie_reviews
from nltk.classify import NaiveBayesClassifier
from nltk.classify.util import accuracy
import re

#import nltk
#nltk.download('movie_reviews')

def extract_features(words):
    return {word: True for word in words}

fileids_pos = movie_reviews.fileids('pos')
fileids_neg = movie_reviews.fileids('neg')

features_pos = [(extract_features(movie_reviews.words(fileids=[f])), 'Positive') for f in fileids_pos]
features_neg = [(extract_features(movie_reviews.words(fileids=[f])), 'Negative') for f in fileids_neg]

num_pos = int(len(features_pos) * 0.8)
num_neg = int(len(features_neg) * 0.8)

features_train = features_pos[:num_pos] + features_neg[:num_neg]
features_test = features_pos[num_pos:] + features_neg[num_neg:]

classifier = NaiveBayesClassifier.train(features_train)
print("Accuracy:", round(accuracy(classifier, features_test), 3))

classifier.show_most_informative_features(20)

manual_reviews = [
    "The film was beautifully directed, emotionally engaging, and wonderfully acted.",
    "The movie was painfully slow, poorly written, and completely boring.",
    "A delightful story with memorable characters and excellent performances.",
    "The plot was confusing, the dialogue was terrible, and the ending was disappointing."
]

for review in manual_reviews:
    words = re.findall(r"[a-z]+", review.lower())
    probabilities = classifier.prob_classify(extract_features(words))

    positive = probabilities.prob('Positive')
    negative = probabilities.prob('Negative')

    result = 'Positive' if positive >= negative else 'Negative'

    print("\nReview:", review)
    print(f"Positive: {positive:.3f} | Negative: {negative:.3f}")
    print("Result:", result)