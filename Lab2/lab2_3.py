from nltk.stem import WordNetLemmatizer

input_words = [
    "walk",
    "walking",
    "walked",
    "walker",
    "sidewalk",
    "sleepwalking",
    "moonwalk",
    "moonshine",
    "moon",
    "buy",
    "elephant"
]

lemmatizer = WordNetLemmatizer()

noun_results = [lemmatizer.lemmatize(word, pos='n') for word in input_words]
verb_results = [lemmatizer.lemmatize(word, pos='v') for word in input_words]

print("Original Noun Verb")
for i in range(len(input_words)):
    print(
        f"{input_words[i]} "
        f"{noun_results[i]} "
        f"{verb_results[i]}"
    )