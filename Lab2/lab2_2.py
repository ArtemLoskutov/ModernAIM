from nltk.stem.porter import PorterStemmer
from nltk.stem.lancaster import LancasterStemmer
from nltk.stem.snowball import SnowballStemmer

input_words = [
    "walk",
    "walking",
    "walked",
    "walker",
    "sidewalk",
    "sleepwalking",
    "moonwalk",
    "moonshine",
    "moon",
    "buy",
    "elephant"
]

porter_results = [PorterStemmer().stem(word) for word in input_words]
lancaster_results = [LancasterStemmer().stem(word) for word in input_words]
snowball_results = [SnowballStemmer("english").stem(word) for word in input_words]

print("original porter lancaster snowball")
for i in range(len(input_words)):
    print(
        f"{input_words[i]} "
        f"{porter_results[i]} "
        f"{lancaster_results[i]} "
        f"{snowball_results[i]}"
    )